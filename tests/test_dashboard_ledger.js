// The loop page's comment trail: parsing the review and coder formats
// (templates/review-format.md, templates/coder-summary.md) into one record per
// comment, the ledger's summary sentence, and the loop view's linked IDs.
// The lifecycle suite invokes this when Node is available.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(process.argv[2], 'utf8');
const moduleScope = { module: { exports: {} } };
vm.runInNewContext(html.match(/<script id="rl-derive">([\s\S]*?)<\/script>/)[1], moduleScope);
const RL = moduleScope.module.exports;
// Values made in the vm context have its own prototypes: compare plain copies.
const plain = x => JSON.parse(JSON.stringify(x));
const eq = (actual, expected, message) => assert.deepEqual(plain(actual), expected, message);

const review1 = `---
verdict: changes_requested
round: 1
---

## Comments

### R1-C1
- severity: high
- blocking: yes
- file: src/greet.py
- line: 10
- description: empty names are accepted
- suggested fix: raise ValueError on ""

### R1-C2
- severity: low
- blocking: no
- file: README.md
- line: 3
- description: the example is out of date
- suggested fix: update it

## Optional

### R1-C3
- severity: low
- blocking: no
- file: src/greet.py
- line: 2
- description: docstring typo
- suggested fix: fix the typo

## Assessment

Not done yet. See R1-C1.

VERDICT: changes_requested`;
const coder2 = `# Round 2

## Responses to the previous review

| ID | Status | Note |
|----|--------|------|
| R1-C1 | fixed | added the check and a test |
| R1-C2 | declined | the README is regenerated by CI |
| R1-C3 | fixed | typo fixed |`;
const review2 = `## Previous comments

- R1-C1: resolved
- R1-C2: declined-accepted — the README is generated
- R1-C3: unresolved — still misspelt

## Comments

### R2-C1
- severity: medium
- blocking: yes
- file: tests/test_greet.py
- line: 8
- description: the new test never runs
- suggested fix: rename it test_*

VERDICT: changes_requested`;

const parsed = RL.parseReviewComments(review1);
eq(parsed.comments.map(c => [c.id, c.optional]), [['R1-C1', false], ['R1-C2', false], ['R1-C3', true]], 'comments and optional findings are read in order');
assert.equal(parsed.comments[0].fields['suggested fix'], 'raise ValueError on ""');
eq(parsed.statuses, [], 'round 1 grades nothing');
eq(RL.parseReviewComments(review2).statuses, [
  { id: 'R1-C1', status: 'resolved', reason: '' },
  { id: 'R1-C2', status: 'declined-accepted', reason: 'the README is generated' },
  { id: 'R1-C3', status: 'unresolved', reason: 'still misspelt' }
], 'earlier IDs are graded with their reasons');
eq(RL.parseCoderResponses(coder2).map(r => [r.id, r.status]), [['R1-C1', 'fixed'], ['R1-C2', 'declined'], ['R1-C3', 'fixed']], 'the response table is read; its header and rule are skipped');
eq(RL.parseCoderResponses('| ID | Status | Note |\n|----|--------|------|\n| R1-C1 | fixed | what changed |').length, 1);
eq(RL.parseReviewComments('VERDICT: approved'), { comments: [], statuses: [] }, 'a review without sections has no comments');

const ledger = RL.commentLedger([{ round: 2, coder: coder2, review: review2 }, { round: 1, coder: '# Round 1', review: review1 }]);
eq(ledger.map(c => c.id), ['R1-C1', 'R1-C2', 'R1-C3', 'R2-C1'], 'comments in the order they were raised, whatever the file order');
const [c1, c2, c3, c4] = ledger;
eq([c1.round, c1.severity, c1.blocking, c1.file, c1.line, c1.description], [1, 'high', true, 'src/greet.py', '10', 'empty names are accepted']);
eq(c1.steps, [{ round: 2, coder: { status: 'fixed', note: 'added the check and a test' }, reviewer: { status: 'resolved', reason: '' } }], 'the coder answer and the reviewer grade of the next round');
assert.equal(c1.status, 'resolved');
assert.equal(c2.status, 'declined-accepted');
assert.equal(c3.optional, true); assert.equal(c3.status, 'unresolved', 'the latest grade wins');
assert.equal(c4.status, 'open', 'a comment nobody graded yet is open');
// A third review that only repeats earlier grades adds no step to the trail.
const review3 = 'VERDICT: approved\n## Previous comments\n\n- R1-C1: resolved\n- R1-C3: resolved\n- R2-C1: resolved\n';
const later = RL.commentLedger([{ round: 1, review: review1 }, { round: 2, coder: coder2, review: review2 }, { round: 3, coder: '| R2-C1 | fixed | renamed |\n| R1-C3 | fixed | spelt right |', review: review3 }]);
eq(later[0].steps.map(x => x.round), [2], 'a repeated grade with no coder answer is dropped');
eq(later[2].steps.map(x => [x.round, x.coder && x.coder.status, x.reviewer && x.reviewer.status]), [[2, 'fixed', 'unresolved'], [3, 'fixed', 'resolved']], 'a changed grade after a new answer is kept');
assert.equal(later[2].status, 'resolved');
eq(c4.steps, []);
for (const c of ledger) assert.ok(RL.COMMENT_STATUS[c.status], `status ${c.status} has a chip`);
// An answer to an ID no review raised (a hand-edited file) is kept, unraised.
const stray = RL.commentLedger([{ round: 2, coder: '| R1-C9 | fixed | ok |', review: '' }]);
eq([stray[0].id, stray[0].raised, stray[0].round], ['R1-C9', false, 1]);

assert.equal(RL.ledgerSummary([]), 'No comments were raised.');
assert.equal(RL.ledgerSummary(ledger), '4 comments, 2 blocking. Still open or unresolved: R2-C1.');
assert.equal(RL.ledgerSummary(ledger.slice(0, 3)), '3 comments, 1 blocking. All blocking comments were resolved.');
assert.equal(RL.ledgerSummary([c2]), '1 comment, 0 blocking.');
assert.equal(RL.ledgerSummary([{ ...c1, status: 'open' }, { ...c4 }]), '2 comments, 2 blocking. 2 still open or unresolved: R1-C1, R2-C1.');

// The loop view: the ledger sits above the rounds, IDs become links that
// never change the hash, and each agent's pane carries its voice colour.
assert.match(html, /<p class="verdict-line">\$\{chip\(l\.outcome\)\} <span>\$\{esc\(RL\.verdictDetail\(l\)\)\}<\/span><\/p>[\s\S]*?\$\{ledgerHtml\(l\)\}[\s\S]*?<details class="run-details">[\s\S]*?\$\{roundsHtml/, 'verdict line, then the ledger, then folded run details, then the rounds');
assert.match(html, /<details class="summary-file"><summary>Loop summary file \(summary\.md\)<\/summary>/, 'summary.md is folded at the end');

// Verdicts come from state.json, or from the review file when a round has no record.
assert.equal(RL.reviewVerdict(review1), 'changes_requested', 'from front matter');
assert.equal(RL.reviewVerdict('## Assessment\n\nOk.\n\nVERDICT: approved'), 'approved', 'from the final VERDICT line');
assert.equal(RL.reviewVerdict('no verdict here'), null);
const loopOf = (files, rounds, st) => ({ files, rounds, st: { max_rounds: 5, ...st }, roundCount: Math.max(rounds.length, files.filter(f => f.review).length), outcome: st.outcome });
const mixed = loopOf([{ round: 1, review: review1 }, { round: 2, review: 'VERDICT: approved' }], [{ round: 1, verdict: 'changes_requested' }], { outcome: 'approved' });
const rv = RL.roundVerdicts(mixed);
eq(rv.list.map(x => [x.round, x.verdict, x.source]), [[1, 'changes_requested', 'state'], [2, 'approved', 'file']], 'a round without a record falls back to its file');
eq([rv.recorded, rv.onDisk, rv.mismatch], [1, 2, true], 'the mismatch is reported');
assert.equal(RL.roundVerdicts(loopOf([{ round: 1, review: review1 }], [{ round: 1, verdict: 'changes_requested' }], {})).mismatch, false);
// One round wording everywhere, and the recap sentence.
assert.equal(RL.roundProgress(loopOf([], [], { active: true, round: 1 })), 'round 1 in progress (round cap 5)');
assert.equal(RL.roundProgress(loopOf([{ round: 1, review: review1 }], [{ round: 1 }], {})), '1 round (round cap 5)');
assert.equal(RL.verdictDetail(mixed), 'In round 2 (round cap 5).', 'the detail never repeats the outcome chip');
assert.equal(RL.loopRecap(mixed, ledger), 'In round 2 (round cap 5). 4 comments, 2 blocking. Still open or unresolved: R2-C1.');
assert.equal(RL.loopRecap(loopOf([], [], { active: true, round: 1, outcome: 'active' }), []), 'Round 1 is in progress (round cap 5).');
assert.equal(RL.loopRecap(loopOf([{ round: 1, review: review1 }], [{ round: 1, verdict: 'changes_requested' }], { outcome: 'max_rounds_reached', max_rounds: 1 }), []),
  'Changes were still requested after 1 round (round cap 1).');
assert.equal(RL.loopRecap(loopOf([], [], { outcome: 'cancelled' }), []), 'After 0 rounds.');
assert.match(html, /<div class="doc coder" role="region"/); assert.match(html, /<div class="doc reviewer" role="region"/);
assert.match(html, /\.doc\.coder \{ border-color: var\(--s1\);/, 'the coder pane is outlined in coder blue');
assert.match(html, /\.doc\.reviewer \{ border-color: var\(--s2\);/, 'the reviewer pane is outlined in reviewer orange');
assert.match(html, /\.doc\.coder \.who::before \{ background: var\(--s1\); \} \.doc\.reviewer \.who::before \{ background: var\(--s2\); \}/, 'each pane label has its voice dot');
assert.match(html, /a\.href = location\.hash \|\| '#'/, 'comment links keep the current route');
assert.match(html, /e\.preventDefault\(\);\s*const at = d\.querySelector\(`\[data-cid-at=/, 'following a comment link scrolls instead of navigating');

// linkComments on a minimal DOM: mentions of raised IDs become links, a
// focusin (the keyboard path) highlights every mention of the same ID, focusout
// clears it, and rendering again does not stack a second set of listeners.
{
  const start = html.indexOf('  function linkComments(');
  const src = html.slice(start, html.indexOf('\n  }\n', start) + 4);
  const listeners = {};
  const cls = () => { const set = new Set(); return { set, toggle: (c, on) => (on ? set.add(c) : set.delete(c)), add: c => set.add(c), remove: c => set.delete(c), contains: c => set.has(c) }; };
  const mention = id => ({ textContent: id, dataset: {}, classList: cls(), closest: () => null, replaceWith(n) { cids[cids.indexOf(this)] = n; } });
  const cids = [mention('R1-C1'), mention('R1-C1'), mention('R1-C2'), mention('R9-C9')];
  const d = {
    dataset: {},
    querySelectorAll: sel => (sel === '.cid' ? [...cids] : []),
    querySelector: () => null,
    addEventListener: (type, fn) => { (listeners[type] = listeners[type] || []).push(fn); }
  };
  const document = { createElement: () => {
    const a = { dataset: {}, attrs: {}, classList: cls(), setAttribute(k, v) { this.attrs[k] = v; } };
    a.closest = sel => (sel === 'a.cid' ? a : null);
    Object.defineProperty(a, 'className', { set(v) { v.split(' ').forEach(c => a.classList.add(c)); } });
    return a;
  } };
  const c = { RL, document, location: { hash: '#/loop/x' } };
  vm.createContext(c);
  vm.runInContext(src + '; this.linkComments = linkComments;', c);
  const loop = { files: [{ round: 1, review: review1 }] };
  c.linkComments(d, loop);
  assert.equal(cids.filter(x => x.dataset && x.dataset.cid).length, 3, 'mentions of raised IDs become links');
  assert.equal(cids[3].dataset.cid, undefined, 'an ID no review raised stays plain text');
  assert.equal(cids[0].href, '#/loop/x', 'a link keeps the current route');
  for (const t of ['mouseover', 'focusin', 'focusout', 'mouseleave', 'click']) assert.equal((listeners[t] || []).length, 1, `${t} is bound once`);
  c.linkComments(d, loop);
  for (const t of ['focusin', 'click']) assert.equal(listeners[t].length, 1, `rendering again does not add another ${t} listener`);
  listeners.focusin[0]({ target: cids[0] });
  eq(cids.map(x => x.classList.contains('hl')), [true, true, false, false], 'keyboard focus highlights every mention of the same ID');
  listeners.focusout[0]({ target: cids[0] });
  eq(cids.map(x => x.classList.contains('hl')), [false, false, false, false], 'leaving the link clears the highlight');
}
assert.match(html, /\.ledger \.lead \{[^}]*text-wrap: pretty;/, 'the ledger lead avoids a lone last word');

// The panes read as an exchange: the review in parts, the coder's answers
// beside their grades, and a status chip that knows whether the loop runs.
{
  const parts = RL.reviewParts(review2);
  eq([parts.structured, parts.statuses.length, parts.comments.map(c => c.id), parts.verdict], [true, 3, ['R2-C1'], 'changes_requested']);
  assert.equal(RL.reviewParts('## Assessment\n\nAll good now.\n\nVERDICT: approved').assessment, 'All good now.', 'assessment text is kept without the VERDICT line');
  assert.doesNotMatch(RL.reviewParts(review1).assessment, /VERDICT/);
  eq(RL.reviewParts(review1).comments.map(c => [c.id, c.optional]), [['R1-C1', false], ['R1-C2', false], ['R1-C3', true]]);
  assert.equal(RL.reviewParts('Looks good to me.\n\nVERDICT: approved').structured, false, 'a free-form review stays markdown');
  eq(RL.reviewParts('## Notes\n\nx\n\n## Assessment\n\nok\n\nVERDICT: approved').other, [{ name: 'notes', text: 'x' }], 'unknown sections are kept');
  const cp = RL.coderParts('# Round 2 — coder summary\n\n## What I did\n\n- fixed\n\n' + coder2.split('\n').slice(2).join('\n') + '\n\n## Open questions\n\n- none');
  assert.doesNotMatch(cp.body, /^# Round/, 'the duplicate round title goes');
  assert.match(cp.body, /## What I did/); assert.match(cp.body, /## Open questions/);
  assert.doesNotMatch(cp.body, /\| R1-C1/, 'the response table is pulled out');
  eq(cp.responses.map(r => [r.id, r.status]), [['R1-C1', 'fixed'], ['R1-C2', 'declined'], ['R1-C3', 'fixed']]);
  const open = { status: 'open', blocking: false, optional: true }, openBlocking = { status: 'open', blocking: true };
  eq(RL.commentStatus(open, true), ['active', 'awaiting the next round']);
  eq(RL.commentStatus(open, false), ['neutral', 'not addressed · optional'], 'an optional comment in a finished loop is not "open"');
  eq(RL.commentStatus({ status: 'open', blocking: false, optional: false }, false), ['neutral', 'not addressed · non-blocking']);
  eq(RL.commentStatus(openBlocking, false), ['serious', 'still open']);
  eq(RL.commentStatus({ status: 'resolved' }, false), ['good', 'resolved']);
  eq(RL.nextStep({ outcome: 'max_rounds_reached' }).cmd, '/review-continue');
  eq(RL.nextStep({ outcome: 'active' }).cmd, '/review-cancel');
  assert.equal(RL.nextStep({ outcome: 'approved' }), null);
  assert.match(html, /<h4 class="who">Coder<\/h4>\$\{coderPane\(f\)\}/, 'the coder pane is named by a heading');
  assert.match(html, /<div class="rc" data-cid-at="\$\{esc\(c\.id\)\}" tabindex="-1">/, 'each raised comment is a link target');
  assert.match(html, /rawFile\('Review file', f\.review\)/, 'the raw review stays one click away');
  assert.match(html, /n && !SHARE \? `<p class="next-step">/, 'next steps never appear on a shared page');
  assert.match(html, /max_rounds_reached: \['serious', 'Round cap reached'\]/, 'the chip names the round cap');
}
