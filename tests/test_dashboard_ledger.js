// linkComments on a minimal DOM: mentions of raised IDs become links, a
// focusin (the keyboard path) highlights every mention of the same ID, focusout
// clears it, and rendering again does not stack a second set of listeners.
{
  const start = html.indexOf('  function linkComments(');
  const src = html.slice(start, html.indexOf('\n  }\n', start) + 4);
  const listeners = {};
  const cls = () => { const set = new Set(); return { set, toggle: (c, on) => (on ? set.add(c) : set.delete(c)), add: c => set.add(c), remove: c => set.delete(c), contains: c => set.has(c) }; };
  const mention = id => ({ textContent: id, dataset: {}, classList: cls(), closest: () => null, replaceWith(n) { cids[cids.indexOf(this)] = n; } });
  const cids = [mention('R1-C1'), mention('R1-C1'), mention('R1-C2'), mention('R9-C9')];
  const d = {
    dataset: {},
    querySelectorAll: sel => (sel === '.cid' ? [...cids] : []),
    querySelector: () => null,
    addEventListener: (type, fn) => { (listeners[type] = listeners[type] || []).push(fn); }
  };
  const document = { createElement: () => {
    const a = { dataset: {}, attrs: {}, classList: cls(), setAttribute(k, v) { this.attrs[k] = v; } };
    a.closest = sel => (sel === 'a.cid' ? a : null);
    Object.defineProperty(a, 'className', { set(v) { v.split(' ').forEach(c => a.classList.add(c)); } });
    return a;
  } };
  const c = { RL, document, location: { hash: '#/loop/x' } };
  vm.createContext(c);
  vm.runInContext(src + '; this.linkComments = linkComments;', c);
  const loop = { files: [{ round: 1, review: review1 }] };
  c.linkComments(d, loop);
  assert.equal(cids.filter(x => x.dataset && x.dataset.cid).length, 3, 'mentions of raised IDs become links');
  assert.equal(cids[3].dataset.cid, undefined, 'an ID no review raised stays plain text');
  assert.equal(cids[0].href, '#/loop/x', 'a link keeps the current route');
  for (const t of ['mouseover', 'focusin', 'focusout', 'mouseleave', 'click']) assert.equal((listeners[t] || []).length, 1, `${t} is bound once`);
  c.linkComments(d, loop);
  for (const t of ['focusin', 'click']) assert.equal(listeners[t].length, 1, `rendering again does not add another ${t} listener`);
  listeners.focusin[0]({ target: cids[0] });
  eq(cids.map(x => x.classList.contains('hl')), [true, true, false, false], 'keyboard focus highlights every mention of the same ID');
  listeners.focusout[0]({ target: cids[0] });
  eq(cids.map(x => x.classList.contains('hl')), [false, false, false, false], 'leaving the link clears the highlight');
}
